using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEditor.Build;
using UnityEngine;
using UnityEngine.Rendering;
using UnityEngine.XR;

/// <summary>
/// Tools > VR Fire Safety > VR Readiness Report
///
/// Writes docs/VR-Readiness-Report.md: a printable summary of everything that decides
/// whether this project can run in a VR headset, filled in from the real project state
/// (packages, OpenXR loader and interaction profiles, player settings, build settings and
/// the scene itself) rather than from memory. It also lists the manual steps that cannot be
/// automated, and what to screenshot for a report or viva.
///
/// The OpenXR types are reached by reflection because the package can be removed with
/// tools/set_xr_packages.py desktop; a hard reference would then stop these Editor scripts
/// from compiling.
/// </summary>
public static class VrReadinessReport
{
    const string ScenePath = "Assets/Scenes/FireSafetyTrainer.unity";
    const string ReportPath = "docs/VR-Readiness-Report.md";

    [MenuItem("Tools/VR Fire Safety/VR Readiness Report", false, 4)]
    public static void WriteReport()
    {
        string markdown;
        try
        {
            markdown = BuildMarkdown();
        }
        catch (Exception error)
        {
            Debug.LogError("[Fire Safety] The VR readiness report failed: " + error.Message);
            return;
        }

        string fullPath = Path.Combine(Directory.GetParent(Application.dataPath).FullName, ReportPath);
        Directory.CreateDirectory(Path.GetDirectoryName(fullPath));
        File.WriteAllText(fullPath, markdown);

        AssetDatabase.Refresh();
        Debug.Log("[Fire Safety] VR readiness report written to " + ReportPath);
        EditorUtility.DisplayDialog("VR readiness report",
            "Written to " + ReportPath + ".\n\nOpen it in any Markdown viewer, or attach it to your " +
            "report. Press Play with Mock HMD enabled to capture the stereo evidence described in " +
            "the last section.", "OK");
    }

    // ------------------------------------------------------------------ //
    // Report
    // ------------------------------------------------------------------ //

    static string BuildMarkdown()
    {
        StringBuilder text = new StringBuilder(8192);
        List<string> failures = new List<string>();

        text.AppendLine("# VR readiness report");
        text.AppendLine();
        text.AppendLine("Generated by **Tools > VR Fire Safety > VR Readiness Report** on " +
                        DateTime.Now.ToString("yyyy-MM-dd HH:mm") + ".");
        text.AppendLine("Everything below was read from the project itself, not typed by hand.");
        text.AppendLine();

        // ---- environment -------------------------------------------------
        text.AppendLine("## 1. Environment");
        text.AppendLine();
        text.AppendLine("| Item | Value |");
        text.AppendLine("| --- | --- |");
        text.AppendLine("| Unity | " + Application.unityVersion + " |");
        text.AppendLine("| Active build target | " + EditorUserBuildSettings.activeBuildTarget + " |");
        text.AppendLine("| Colour space | " + PlayerSettings.colorSpace + " |");
        text.AppendLine("| Render pipeline | " + PipelineName() + " |");
        text.AppendLine("| Active input handling | " + InputHandlingName() + " |");
        text.AppendLine();

        // ---- packages ----------------------------------------------------
        text.AppendLine("## 2. XR packages");
        text.AppendLine();
        text.AppendLine("| Package | Version in `Packages/manifest.json` |");
        text.AppendLine("| --- | --- |");
        string[] packages =
        {
            "com.unity.xr.openxr", "com.unity.xr.management", "com.unity.xr.interaction.toolkit",
            "com.unity.render-pipelines.universal",
        };
        foreach (string package in packages)
        {
            string version = ManifestVersion(package);
            text.AppendLine("| " + package + " | " + (version ?? "**not installed**") + " |");
            if (version == null && package == "com.unity.xr.openxr")
                failures.Add("The OpenXR package is not in Packages/manifest.json.");
        }
        text.AppendLine();

        // ---- OpenXR ------------------------------------------------------
        text.AppendLine("## 3. OpenXR configuration");
        text.AppendLine();
        string openXrState = DescribeOpenXr(failures);
        text.AppendLine(openXrState);
        text.AppendLine();

        // ---- headset build -----------------------------------------------
        text.AppendLine("## 4. Standalone headset build settings");
        text.AppendLine();
        text.AppendLine("| Setting | Value | Required |");
        text.AppendLine("| --- | --- | --- |");
        text.AppendLine("| Target architecture | " + AndroidArchitectures() + " | ARM64 |");
        text.AppendLine("| Minimum API level | " + PlayerSettings.Android.minSdkVersion + " | 29+ |");
        text.AppendLine("| Scripting backend (Android) | " + AndroidScriptingBackend() + " | IL2CPP |");
        text.AppendLine("| Bundle identifier (Android) | " + BundleId() + " | any unique id |");
        text.AppendLine("| Scene in Build Settings | " + SceneInBuild() + " | the training scene |");
        text.AppendLine();

        if (PlayerSettings.Android.targetArchitectures != AndroidArchitecture.ARM64 &&
            (PlayerSettings.Android.targetArchitectures & AndroidArchitecture.ARM64) == 0)
            failures.Add("Android target architecture does not include ARM64, which every current " +
                         "standalone headset requires.");
        if ((int)PlayerSettings.Android.minSdkVersion < 29)
            failures.Add("Android minimum API level is below 29.");

        // ---- scene -------------------------------------------------------
        text.AppendLine("## 5. Scene and XR rendering");
        text.AppendLine();
        text.AppendLine("| Item | Value |");
        text.AppendLine("| --- | --- |");
        text.AppendLine("| Scene | `" + ScenePath + "` |");
        text.AppendLine("| Main Camera has XR rendering enabled | " + CameraXrAllowed() + " |");
        text.AppendLine("| Player rig | `Player` > `Main Camera`, `CharacterController` on the rig " +
                        "root, head pose written by `PlayerController` |");
        text.AppendLine("| Tracking origin | requested as **floor-relative** every second until the " +
                        "XR input subsystem is running; falls back to a 1.62 m eye offset |");
        text.AppendLine("| Input path | `UnityEngine.XR.InputDevices` — left stick move, right stick " +
                        "snap turn, trigger interact, head pose |");
        text.AppendLine("| Runtime diagnostics | `VrReadinessPanel` on the Player — press **F2** in " +
                        "Play mode |");
        text.AppendLine();

        // ---- manual steps ------------------------------------------------
        text.AppendLine("## 6. Manual steps (cannot be automated)");
        text.AppendLine();
        text.AppendLine("Tick these in the Editor. They are per-project settings that Unity writes " +
                        "itself when the OpenXR loader is enabled, so they cannot be shipped in the " +
                        "repository.");
        text.AppendLine();
        text.AppendLine("- [ ] **Project Settings > XR Plug-in Management > PC**: OpenXR ticked" +
                        " (Android tab too, for a standalone build)");
        text.AppendLine("- [ ] **XR Plug-in Management > OpenXR > Enabled Interaction Profiles**: " +
                        "the profile for your controllers added");
        text.AppendLine("- [ ] **XR Plug-in Management > OpenXR > Play Mode OpenXR Runtime**: a runtime " +
                        "is listed (start Meta Quest Link / SteamVR first)");
        text.AppendLine("- [ ] Render Mode left on **Single Pass Instanced**");
        text.AppendLine("- [ ] Active Input Handling left on **Both**");
        text.AppendLine();

        // ---- evidence ----------------------------------------------------
        text.AppendLine("## 7. How to evidence VR readiness without a headset");
        text.AppendLine();
        text.AppendLine("1. **Stereo rendering.** Package Manager > + > *Add package by name…* > " +
                        "`com.unity.xr.mock-hmd`, enable **Mock HMD** in XR Plug-in Management, press " +
                        "Play. Use the Game view render-mode dropdown (above the Game view) and choose " +
                        "**Both Eyes**: the window now shows the scene twice, side by side, which is " +
                        "the stereo path the headset receives. Screenshot that.");
        text.AppendLine("2. **Live XR state.** With Mock HMD active, press **F2** in Play mode. The " +
                        "panel reports `XR session ....... ACTIVE`, the stereo mode, the eye resolution " +
                        "scale and the controllers the runtime reports. Screenshot it.");
        text.AppendLine("3. **Configuration.** Screenshot *XR Plug-in Management* (OpenXR ticked), the " +
                        "*OpenXR* page (interaction profile listed, Play Mode runtime named) and " +
                        "*Player > Other Settings* (Active Input Handling = Both, IL2CPP, ARM64, API 29).");
        text.AppendLine("4. **This report.** `Tools > VR Fire Safety > VR Readiness Report` regenerates " +
                        "`docs/VR-Readiness-Report.md` from the live project state.");
        text.AppendLine("5. **Build proof.** File > Build Settings > Android > *Build* (not *Build And " +
                        "Run*). A successful APK proves the XR plugin, IL2CPP, ARM64 and the shaders " +
                        "compile for the headset, even with no device attached.");
        text.AppendLine("6. **Honest wording.** Say: the VR path is implemented and configuration-verified; " +
                        "it was exercised in the Editor with the Mock HMD runtime, not on a physical " +
                        "headset.");
        text.AppendLine();

        // ---- verdict -----------------------------------------------------
        text.AppendLine("## 8. Verdict");
        text.AppendLine();
        if (failures.Count == 0)
        {
            text.AppendLine("**No automated problems found.** The project is configured for XR input, " +
                            "URP stereo rendering and an ARM64 standalone headset build; the remaining " +
                            "items in section 6 are Editor clicks.");
        }
        else
        {
            text.AppendLine("**" + failures.Count + " issue(s) found:**");
            text.AppendLine();
            foreach (string failure in failures) text.AppendLine("- " + failure);
        }
        text.AppendLine();
        return text.ToString();
    }

    // ------------------------------------------------------------------ //
    // Helpers
    // ------------------------------------------------------------------ //

    static string PipelineName()
    {
        try
        {
            RenderPipelineAsset pipeline = GraphicsSettings.defaultRenderPipeline;
            return pipeline == null ? "Built-in (no pipeline asset)" : pipeline.name + " (SRP)";
        }
        catch (Exception)
        {
            return "unknown";
        }
    }

    /// <summary>Player Settings > Active Input Handling, read through serialization.</summary>
    static string InputHandlingName()
    {
        UnityEngine.Object[] assets =
            AssetDatabase.LoadAllAssetsAtPath("ProjectSettings/ProjectSettings.asset");
        if (assets == null || assets.Length == 0) return "unknown";
        SerializedProperty property = new SerializedObject(assets[0]).FindProperty("activeInputHandler");
        if (property == null) return "unknown";
        switch (property.intValue)
        {
            case 0: return "Input Manager (Old)";
            case 1: return "Input System Package (New)";
            case 2: return "Both";
            default: return "unknown";
        }
    }

    static string ManifestVersion(string package)
    {
        try
        {
            string manifest = Path.Combine(Directory.GetParent(Application.dataPath).FullName,
                                           "Packages/manifest.json");
            if (!File.Exists(manifest)) return null;
            Match match = Regex.Match(File.ReadAllText(manifest),
                "\"" + Regex.Escape(package) + "\"\\s*:\\s*\"([^\"]+)\"");
            return match.Success ? match.Groups[1].Value : null;
        }
        catch (Exception)
        {
            return null;
        }
    }

    /// <summary>Reads the OpenXR loader state and the enabled interaction profiles.</summary>
    static string DescribeOpenXr(List<string> failures)
    {
        Type settingsType = Type.GetType("UnityEngine.XR.OpenXR.OpenXRSettings, Unity.XR.OpenXR");
        if (settingsType == null)
        {
            failures.Add("The OpenXR package is not installed, so no headset runtime is available.");
            return "OpenXR package: **not installed**.";
        }

        object settings = null;
        try
        {
            PropertyInfo active = settingsType.GetProperty("ActiveBuildTargetInstance",
                BindingFlags.Public | BindingFlags.Static);
            if (active != null) settings = active.GetValue(null);
        }
        catch (Exception)
        {
            settings = null;
        }

        if (settings == null)
        {
            failures.Add("No OpenXR settings exist for the active build target: the OpenXR loader is " +
                         "not enabled in XR Plug-in Management.");
            return "OpenXR is installed but **no settings asset exists for " +
                   EditorUserBuildSettings.activeBuildTarget +
                   "** — enable the OpenXR loader in XR Plug-in Management.";
        }

        MethodInfo getFeatures = settingsType.GetMethod("GetFeatures", Type.EmptyTypes);
        Array features = getFeatures != null
            ? getFeatures.Invoke(settings, null) as Array
            : null;

        List<string> enabled = new List<string>();
        List<string> profiles = new List<string>();
        if (features != null)
        {
            foreach (object feature in features)
            {
                if (feature == null) continue;
                Type type = feature.GetType();
                if (!IsEnabled(feature, type)) continue;
                enabled.Add(type.Name);
                if (IsInteractionProfile(type)) profiles.Add(ReadableName(type.Name));
            }
        }

        StringBuilder text = new StringBuilder();
        text.AppendLine("Enabled features for " + EditorUserBuildSettings.activeBuildTarget + ": " +
                        (enabled.Count == 0 ? "**none**" : string.Join(", ", enabled.ToArray())));
        text.AppendLine();
        text.AppendLine("Enabled interaction profiles: " +
                        (profiles.Count == 0 ? "**none**" : string.Join(", ", profiles.ToArray())));

        if (enabled.Count == 0)
            failures.Add("No OpenXR features are enabled: the headset will not be used at all.");
        else if (profiles.Count == 0)
            failures.Add("No controller interaction profile is enabled: the headset will track, but " +
                         "the thumbsticks and trigger will do nothing.");

        string devices = XRSettings.supportedDevices == null || XRSettings.supportedDevices.Length == 0
            ? "none"
            : string.Join(", ", XRSettings.supportedDevices);
        text.AppendLine();
        text.AppendLine("XR devices enabled for the build: " + devices + ".");
        if (devices == "none")
            failures.Add("The build has no XR device enabled (XR Plug-in Management > OpenXR is not ticked).");
        return text.ToString();
    }

    static bool IsEnabled(object feature, Type type)
    {
        PropertyInfo property = type.GetProperty("enabled",
            BindingFlags.Public | BindingFlags.Instance);
        if (property == null || property.PropertyType != typeof(bool)) return false;
        try
        {
            return (bool)property.GetValue(feature, null);
        }
        catch (Exception)
        {
            return false;
        }
    }

    static bool IsInteractionProfile(Type type)
    {
        for (Type current = type; current != null; current = current.BaseType)
            if (current.Name == "OpenXRInteractionFeature") return true;
        return false;
    }

    static string ReadableName(string typeName)
    {
        if (typeName.EndsWith("Profile", StringComparison.Ordinal))
            typeName = typeName.Substring(0, typeName.Length - "Profile".Length);
        StringBuilder builder = new StringBuilder(typeName.Length + 8);
        for (int i = 0; i < typeName.Length; i++)
        {
            if (i > 0 && char.IsUpper(typeName[i])) builder.Append(' ');
            builder.Append(typeName[i]);
        }
        return builder.ToString();
    }

    static string AndroidArchitectures()
    {
        AndroidArchitecture architecture = PlayerSettings.Android.targetArchitectures;
        List<string> names = new List<string>();
        if ((architecture & AndroidArchitecture.ARMv7) != 0) names.Add("ARMv7");
        if ((architecture & AndroidArchitecture.ARM64) != 0) names.Add("ARM64");
        if ((architecture & AndroidArchitecture.X86) != 0) names.Add("x86");
        if ((architecture & AndroidArchitecture.X86_64) != 0) names.Add("x86_64");
        return names.Count == 0 ? architecture.ToString() : string.Join(", ", names.ToArray());
    }

    static string AndroidScriptingBackend()
    {
        try
        {
            return PlayerSettings.GetScriptingBackend(NamedBuildTarget.Android).ToString();
        }
        catch (Exception)
        {
            return "unknown";
        }
    }

    static string BundleId()
    {
        try
        {
            return PlayerSettings.GetApplicationIdentifier(NamedBuildTarget.Android);
        }
        catch (Exception)
        {
            return "unknown (open Player > Android to read it)";
        }
    }

    static string SceneInBuild()
    {
        foreach (EditorBuildSettingsScene scene in EditorBuildSettings.scenes)
            if (scene.path == ScenePath) return scene.enabled ? "yes (enabled)" : "yes (disabled)";
        return "**no**";
    }

    /// <summary>The scene file records URP's per-camera XR flag, which no public API exposes.</summary>
    static string CameraXrAllowed()
    {
        try
        {
            string path = Path.Combine(Directory.GetParent(Application.dataPath).FullName, ScenePath);
            if (!File.Exists(path)) return "scene missing";
            string text = File.ReadAllText(path);
            MatchCollection matches = Regex.Matches(text, "m_AllowXRRendering:\\s*(\\d)");
            if (matches.Count == 0) return "flag not found";
            foreach (Match match in matches)
                if (match.Groups[1].Value != "1") return "**no**";
            return "yes (" + matches.Count + " camera data block(s))";
        }
        catch (Exception)
        {
            return "unknown";
        }
    }
}
